def esc(s):
    return html.escape(str(s), quote=True)


def lp(lang):
    return "" if lang == "en" else "/" + lang


def path_home(lang):
    return lp(lang) + "/"


def path_page(lang, slug):
    return "%s/%s/" % (lp(lang), slug)


def url(path):
    return SITE + path


def user_href(target, path, cur):
    return path + "?lang=en" if target == "en" and cur != "en" else path


def parse_front(text):
    m = re.match(r"^---\n(.*?)\n---[ \t]*\n?(.*)$", text, re.S)
    if not m:
        raise ValueError("no front matter")
    meta = {}
    for line in m.group(1).splitlines():
        if line.strip():
            k, sep, v = line.partition(":")
            if not sep:
                raise ValueError("bad front matter line: %r" % line)
            meta[k.strip()] = v.strip().strip("\"'")
    return meta, m.group(2).strip("\n")


def inline(s):
    s = esc(s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)",
               lambda m: '<a href="%s"%s>%s</a>' % (m.group(2), ' rel="noopener"' if m.group(2).startswith("http") else "", m.group(1)), s)
    return re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)


def markdown(text):
    out, para, items = [], [], []

    def flush():
        if para:
            out.append("<p>%s</p>" % inline(" ".join(para)))
            para.clear()
        if items:
            out.append("<ul>%s</ul>" % "".join("<li>%s</li>" % inline(x) for x in items))
            items.clear()

    for ln in text.split("\n"):
        s = ln.strip()
        m = re.match(r"^(#{2,3})\s+(.*)$", s)
        if not s:
            flush()
        elif m:
            flush()
            out.append("<h%d>%s</h%d>" % (len(m.group(1)), inline(m.group(2)), len(m.group(1))))
        elif re.match(r"^[-*]\s+", s):
            if para:
                flush()
            items.append(re.sub(r"^[-*]\s+", "", s))
        else:
            if items:
                flush()
            para.append(s)
    flush()
    return "\n".join(out)


def problems(where, text):
    errs = ["%s: forbidden text %r" % (where, b) for b in FORBIDDEN if b in text]
    if EMOJI.search(text):
        errs.append("%s: emoji are not allowed" % where)
    if PRICE.search(text):
        errs.append("%s: price / rating / store wording %r" % (where, PRICE.search(text).group(0)))
    return errs


class Ctx:
    def __init__(self, root):
        self.root = Path(root)
        self.errs = []
        self.i18n, self.pages = {}, {}
        for f in sorted((self.root / "content" / "i18n").glob("*.json")):
            tag = languages.from_legacy(f.stem)
            if languages.is_ended(tag):
                continue
            if tag not in languages.SUPPORTED:
                self.errs.append("i18n/%s.json: unknown language" % f.stem)
                continue
            d = json.loads(f.read_text(encoding="utf-8"))
            for k in KEYS:
                if not str(d.get(k, "")).strip():
                    self.errs.append("i18n/%s.json: missing %s" % (f.stem, k))
            for k in d:
                if k not in KEYS:
                    self.errs.append("i18n/%s.json: unknown key %s" % (f.stem, k))
            self.errs += problems("i18n/%s.json" % f.stem, json.dumps(d, ensure_ascii=False))
            self.i18n[tag] = d
        self.langs = [l for l in languages.SUPPORTED if l in self.i18n]
        for l in self.langs:
            for slug in PAGE_SLUGS:
                f = self.root / "content" / "pages" / languages.legacy_code(l) / (slug + ".md")
                if not f.exists():
                    self.errs.append("pages/%s/%s.md: missing" % (l, slug))
                    continue
                try:
                    meta, body = parse_front(f.read_text(encoding="utf-8"))
                except ValueError as ex:
                    self.errs.append("pages/%s/%s.md: %s" % (l, slug, ex))
                    continue
                for k in ("title", "description", "updated"):
                    if not meta.get(k):
                        self.errs.append("pages/%s/%s.md: front matter %s" % (l, slug, k))
                self.errs += problems("pages/%s/%s.md" % (l, slug), f.read_text(encoding="utf-8"))
                if self.sub_missing(body):
                    self.errs.append("pages/%s/%s.md: unknown placeholder" % (l, slug))
                self.pages[(l, slug)] = (meta, body)

    @staticmethod
    def sub_missing(body):
        return [p for p in re.findall(r"\{\{(\w+)\}\}", body) if p not in ("OPERATOR", "EMAIL", "EFFECTIVE", "SITE")]

    def t(self, lang, key):
        return self.i18n[lang][key]

    def sub(self, text):
        return text.replace("{{OPERATOR}}", OPERATOR).replace("{{EMAIL}}", EMAIL).replace("{{EFFECTIVE}}", EFFECTIVE).replace("{{SITE}}", SITE)


def langpick_script(ctx, available):
    src = (ctx.root / "assets" / "langpick.js").read_text(encoding="utf-8")
    src = re.sub(r"/\*.*?\*/", "", src, count=1, flags=re.S)
    src = src.replace("/*SUPPORTED*/[]", json.dumps(ctx.langs)).replace("/*AVAILABLE*/[]", json.dumps([l for l in available if l != "en"]))
    return "<script>%s</script>" % re.sub(r"\s*\n\s*", "", src).strip()


def render(ctx, lang, *, path, title, desc, body, alt, updated, nav="", noindex=False, ai=False):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    og_loc = OG_LOCALE[lang]
    head = ['<meta charset="utf-8">', '<meta name="viewport" content="width=device-width,initial-scale=1">',
            "<title>%s</title>" % esc(title), '<meta name="description" content="%s">' % esc(desc),
            '<meta name="robots" content="%s">' % ("noindex,follow" if noindex else "index,follow,max-image-preview:large")]
    if not noindex:
        head.append('<link rel="canonical" href="%s">' % esc(url(path)))
        head.append(seo.alternate_links([(languages.hreflang(l), url(p)) for l, p in alt.items()], x_default=url(alt["en"])))
        head += ['<meta property="og:type" content="website">', '<meta property="og:site_name" content="Patchland">',
                 '<meta property="og:title" content="%s">' % esc(title), '<meta property="og:description" content="%s">' % esc(desc),
                 '<meta property="og:url" content="%s">' % esc(url(path)), '<meta property="og:locale" content="%s">' % og_loc]
    head += ['<meta name="color-scheme" content="light dark">', '<meta name="theme-color" content="#F6F1E7">',
             '<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">',
             '<link rel="stylesheet" href="/assets/patchland.css?v=%s">' % ASSET_V]
    if lang == "en" and not noindex:
        head.append("<!--LANGPICK-->")
    ld = {"@context": "https://schema.org", "@graph": [ORG, {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": "Patchland",
                                                              "inLanguage": lang, "publisher": {"@id": ORG["@id"]}}]}
    head.append('<script type="application/ld+json">%s</script>' % json.dumps(ld, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"))
    switch = "".join('<a href="%s" hreflang="%s" lang="%s"%s aria-label="%s">%s</a>' % (
        esc(user_href(l, alt.get(l) or path_home(l), lang)), l, l, ' aria-current="true"' if l == lang else "", esc(languages.NAMES[l]), l.split("-")[0].upper())
        for l in ctx.langs)
    navs = [(path_home(lang), t("nav_home"), "home"), (path_page(lang, "support"), t("nav_support"), "support")]
    nav_html = "".join('<a href="%s"%s>%s</a>' % (esc(h), ' aria-current="page"' if nav == k else "", esc(label)) for h, label, k in navs)
    logo = ('<i aria-hidden="true">%s</i>' % "".join('<b style="background:%s"></b>' % c for c in PAPER[:4]))
    header = ('<header class="site-header"><div class="wrap bar"><a class="brand" href="%s" aria-label="Patchland">%s<span>Patchland</span></a>'
              '<nav class="nav" aria-label="%s">%s</nav></div><div class="wrap"><div class="langsw" role="group" aria-label="%s">%s</div></div></header>') % (
        esc(path_home(lang)), logo, esc(t("aria_main")), nav_html, esc(t("lang_label")), switch)
    foot_links = "".join('<a href="%s">%s</a>' % (esc(h), esc(l)) for h, l in
                         [(path_page(lang, "support"), t("nav_support")), (path_page(lang, "privacy"), t("nav_privacy")), (path_page(lang, "terms"), t("nav_terms"))])
    foot_langs = " ".join('<a href="%s" hreflang="%s" lang="%s"%s>%s</a>' % (
        esc(user_href(l, alt.get(l) or path_home(l), lang)), l, l, ' aria-current="true"' if l == lang else "", esc(languages.NAMES[l])) for l in ctx.langs)
    footer = ('<footer class="site-footer"><div class="wrap"><p>%s <a href="https://ipe.rest/">ipe.rest</a></p><p class="foot-links">%s</p>'
              '<p class="foot-langs">%s</p><p>© 2026 ipe() · %s</p></div></footer>') % (
        esc(t("footer_line")), foot_links, foot_langs, esc(t("status_badge")))
    notice = ""
    if ai:
        notice = '<p class="ai-note">%s <a href="%s">%s</a></p>' % (esc(t("ai_note")), esc(alt["en"]), esc(t("ai_orig")))
    last = '<p class="updated">%s: <time datetime="%s">%s</time></p>' % (esc(t("updated_label")), esc(updated), esc(updated)) if updated else ""
    return ('<!doctype html>\n<!-- %s -->\n<html lang="%s"><head>%s</head><body><a class="skip" href="#main">%s</a>%s<main id="main" class="wrap%s">%s%s%s</main>%s</body></html>\n') % (
        GEN_MARK, lang, "\n".join(head), esc(t("skip")), header, " doc" if nav != "home" else "", notice, body, last, footer)


def build_home(ctx, lang):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    h1 = esc(t("hero_h1")).replace("|", "<br>")
    art = "".join('<span style="background:%s"></span>' % c for c in PAPER)
    cards = "".join(
        '<article class="card game" style="--c:%s"><h3>%s</h3><p>%s</p></article>' % (GAME_COLORS[g], esc(t("g_" + g)), esc(t("g_%s_p" % g))) for g in GAMES)
    feats = "".join("<li>%s</li>" % esc(t("feat%d" % i)) for i in range(1, 7))
    body = ('<section class="hero"><div><p class="badge">%s</p><h1>%s</h1><p class="lead">%s</p><p><a class="btn" href="#games">%s</a></p><p class="note">%s</p></div>'
            '<div class="hero-art" aria-hidden="true">%s</div></section>'
            '<section class="section" id="games"><h2>%s</h2><p class="lead">%s</p><div class="grid">%s</div><p class="more">%s</p></section>'
            '<section class="section"><h2>%s</h2><ul class="facts">%s</ul></section>'
            '<section class="section cta"><h2>%s</h2><p>%s</p></section>') % (
        esc(t("status_badge")), h1, esc(t("hero_p")), esc(t("games_h")), esc(t("hero_note")), art, esc(t("games_h")), esc(t("games_p")), cards,
        esc(t("more_games")), esc(t("feat_h")), feats, esc(t("cta_h")), esc(t("cta_p")))
    alt = {l: path_home(l) for l in ctx.langs}
    return render(ctx, lang, path=path_home(lang), title=t("home_title"), desc=t("home_desc"), body=body, alt=alt, updated=SITE_UPDATED,
                  nav="home", ai=lang not in ORIGINALS).replace('<main id="main" class="wrap">', '<main id="main" class="wrap">')


def build_page(ctx, lang, slug):
    meta, body = ctx.pages[(lang, slug)]
    alt = {l: path_page(l, slug) for l in ctx.langs}
    html_body = "<h1>%s</h1>\n%s" % (esc(meta["title"]), markdown(ctx.sub(body)))
    return render(ctx, lang, path=path_page(lang, slug), title="%s — Patchland" % meta["title"], desc=meta["description"], body=html_body, alt=alt,
                  updated=meta["updated"], nav=slug, ai=lang not in ORIGINALS)


def build_404(ctx):
    t = lambda k: ctx.t("en", k)  # noqa: E731
    body = '<h1>404</h1><p class="lead">%s</p><p><a class="btn" href="/">%s</a></p>' % (esc(t("nf_p")), esc(t("nav_home")))
    return render(ctx, "en", path="/404.html", title="404 — Patchland", desc=t("nf_h"), body=body, alt={"en": "/"}, updated="", noindex=True)


def sitemap(ctx):
    rows = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- %s -->" % GEN_MARK,
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    ents = [(path_home(l), SITE_UPDATED, {x: path_home(x) for x in ctx.langs}) for l in ctx.langs]
    for slug in PAGE_SLUGS:
        for l in ctx.langs:
            ents.append((path_page(l, slug), ctx.pages[(l, slug)][0]["updated"], {x: path_page(x, slug) for x in ctx.langs}))
    for pth, lm, alts in ents:
        rows.append("<url><loc>%s</loc><lastmod>%s</lastmod>" % (esc(url(pth)), lm))
        for l, ap in alts.items():
            rows.append('<xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (l, esc(url(ap))))
        rows.append('<xhtml:link rel="alternate" hreflang="x-default" href="%s"/></url>' % esc(url(alts["en"])))
    rows.append("</urlset>")
    return "\n".join(rows) + "\n"


def robots():
    return "# %s\nUser-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n" % (GEN_MARK, SITE)


def llms(ctx):
    en = ctx.i18n["en"]
    return "\n".join([
        "# Patchland: Claim It All", "", "> %s" % en["home_desc"], "",
        "Patchland is an offline territory game by ipe() (https://ipe.rest/) for iOS and Android. It has NOT been released: no store page, price or release date exists yet. "
        "The game app and this website collect no personal information, use no analytics or ads and set no cookies.", "",
        "## Pages", "", "- [Home](%s/)" % SITE, "- [Support](%s/support/)" % SITE, "- [Privacy Policy](%s/privacy/)" % SITE, "- [Terms of Use](%s/terms/)" % SITE, "",
        "## Languages", "", "English (original) and Korean (original); %s are AI translations under /<code>/." % ", ".join(
            l for l in ctx.langs if l not in ORIGINALS), ""])


def build_all(ctx):
    files = {"404.html": build_404(ctx), "sitemap.xml": sitemap(ctx), "robots.txt": robots(), "llms.txt": llms(ctx)}
    for l in ctx.langs:
        files[path_home(l).strip("/") + "/index.html" if l != "en" else "index.html"] = build_home(ctx, l)
        for slug in PAGE_SLUGS:
            files[path_page(l, slug).strip("/") + "/index.html"] = build_page(ctx, l, slug)
    for old, (to, note) in MOVED.items():
        for tail in ("", "privacy/", "support/", "terms/"):
            dest = to + tail if old == "pt" else to
            files["%s/%sindex.html" % (old, tail)] = moved_stub(old, dest, note)
    for f, text in files.items():
        if f.endswith(".html") and "<!--LANGPICK-->" in text:
            slug = "" if f == "index.html" else f[: -len("index.html")].strip("/")
            avail = [l for l in ctx.langs if slug == "" or slug in PAGE_SLUGS]
            files[f] = text.replace("<!--LANGPICK-->", langpick_script(ctx, avail))
    return files


GEN_DIRS = ["privacy", "support", "terms"] + [l for l in languages.SUPPORTED if l != "en"] + list(MOVED)


def moved_stub(old, to, note):
    """Static hosting: an old path (/pt/..., /zh/..., /ru/...) becomes a tiny noindex page that forwards with meta refresh."""
    return ('<!doctype html>\n<!-- %s -->\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            '<title>Patchland</title><meta name="robots" content="noindex,follow"><meta http-equiv="refresh" content="0;url=%s">'
            '<link rel="canonical" href="%s"></head><body><p>%s <a href="%s">%s</a></p></body></html>\n') % (GEN_MARK, esc(to), esc(url(to)), esc(note), esc(to), esc(to))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(HERE))
    a = ap.parse_args(argv)
    ctx = Ctx(a.root)
    if ctx.errs:
        print("\n".join(ctx.errs), file=sys.stderr)
        return 1
    if a.check:
        print("sources ok: %d languages, %d pages" % (len(ctx.langs), len(ctx.pages)))
        return 0
    root = Path(a.root)
    for d in GEN_DIRS:
        shutil.rmtree(root / d, ignore_errors=True)
    files = build_all(ctx)
    for f, text in files.items():
        p = root / f
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print("built %d files" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
